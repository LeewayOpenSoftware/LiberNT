import re
import sys
import xml.etree.ElementTree as ET

INT64 = {
    'GLintptr', 'GLsizeiptr', 'GLintptrARB', 'GLsizeiptrARB', 'GLint64', 'GLuint64', 'GLint64EXT',
    'GLuint64EXT', 'GLsync', 'GLeglImageOES', 'GLeglClientBufferEXT', 'GLvdpauSurfaceNV', 'GLDEBUGPROC',
    'GLDEBUGPROCARB', 'GLDEBUGPROCKHR', 'GLDEBUGPROCAMD', 'GLVULKANPROCNV',
}
INT32 = {
    'GLenum', 'GLbitfield', 'GLint', 'GLuint', 'GLsizei', 'GLfixed', 'GLclampx', 'GLhandleARB', 'int',
    'unsigned int', 'GLuint', 'GLclampx',
}
TYPES = {
    'GLshort': 'h', 'GLushort': 'H', 'GLhalf': 'H', 'GLhalfARB': 'H', 'GLhalfNV': 'H', 'GLbyte': 'b',
    'GLchar': 'b', 'GLcharARB': 'b', 'GLboolean': 'B', 'GLubyte': 'B', 'GLfloat': 'f', 'GLclampf': 'f',
    'GLdouble': 'd', 'GLclampd': 'd', 'void': 'v',
}


def declaration(element):
    parts = [element.text or '']
    for child in element:
        if child.tag != 'name':
            parts.append(child.text or '')
        parts.append(child.tail or '')
    return ' '.join(''.join(parts).split())


def classify(text, command):
    if '*' in text or '[' in text:
        return 'q'
    base = ' '.join(word for word in text.split() if word not in ('const', 'struct'))
    if base in INT64:
        return 'q'
    if base in INT32:
        return 'w'
    if base in TYPES:
        return TYPES[base]
    sys.exit('glsig: unknown type "%s" in %s' % (text, command))


def main():
    gl_xml, icd_h, output = sys.argv[1:4]
    signatures = {}
    for command in ET.parse(gl_xml).getroot().find('commands').findall('command'):
        proto = command.find('proto')
        name = proto.find('name').text
        signature = classify(declaration(proto), name)
        for param in command.findall('param'):
            kind = classify(declaration(param), name)
            if kind == 'v':
                sys.exit('glsig: void parameter in %s' % name)
            signature += kind
        signatures[name] = signature

    with open(icd_h, encoding='utf-8') as source:
        text = source.read()
    body = text[text.index('struct __GLdispatchTableRec'):]
    body = body[:body.index('};')]
    table = re.findall(r'\(GLAPIENTRY \* (\w+)\)', body)
    if len(table) != 336:
        sys.exit('glsig: the OpenGL 1.1 table has %d entries' % len(table))

    with open(output, 'w', encoding='utf-8') as out:
        out.write('/* Generated by glsig.py from gl.xml and icd.h. */\n\n')
        out.write('#include "glsig.h"\n\n')
        out.write('const GLTHUNK_SIGNATURE GlThunkSignatures[] =\n{\n')
        for name in sorted(signatures):
            out.write('    { "%s", "%s" },\n' % (name, signatures[name]))
        out.write('};\n\n')
        out.write('const unsigned int GlThunkSignatureCount = %d;\n\n' % len(signatures))
        out.write('const char *const GlThunkTableSignatures[%d] =\n{\n' % len(table))
        for name in table:
            out.write('    "%s",\n' % signatures['gl' + name])
        out.write('};\n')


main()
